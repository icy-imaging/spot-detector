package plugins.fab.spotDetector.roi;

import org.apache.poi.ss.usermodel.Sheet;
import fr.icy.extension.kernel.roi.descriptor.measure.ROIInteriorDescriptor;
import fr.icy.io.xls.XLSXUtil;
import fr.icy.io.xml.XMLUtil;
import fr.icy.model.roi.ROI;
import org.jetbrains.annotations.NotNull;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import plugins.fab.spotDetector.DetectionSpot;
import plugins.fab.spotDetector.GlobalDetectionToken;

import java.util.ArrayList;
import java.util.HashMap;

public class ROI_XLS_Common_Saver {
    public static void saveXLS(final @NotNull Sheet page, final @NotNull GlobalDetectionToken gdt, final String ROIGeneratorName) throws InterruptedException {
        int row = page.getLastRowNum();

        // int row = page.getExcelPage().getRows();
        XLSXUtil.setCellString(page, 0, row, "Region of interest generated by : ");
        // page.setLabel( 0 , row , "Region of interest generated by : " );
        XLSXUtil.setCellString(page, 1, row, ROIGeneratorName);
        // page.setLabel( 1 , row , ROIGeneratorName );

        row++;

        final HashMap<ROI, ArrayList<DetectionSpot>> ROI2Detection = gdt.roi2detection;

        XLSXUtil.setCellString(page, 0, row, "ROI number");
        // page.setLabel( 0 , row , "ROI number" );
        XLSXUtil.setCellString(page, 1, row, "ROI name");
        // page.setLabel( 1 , row , "ROI name" );
        // xlsManager.setLabel( 1 , row , "ROI color" );
        XLSXUtil.setCellString(page, 2, row, "ROI surface");
        // page.setLabel( 2 , row , "ROI surface" );
        XLSXUtil.setCellString(page, 3, row, "ROI nb detection");
        // page.setLabel( 3 , row , "ROI nb detection" );
        XLSXUtil.setCellString(page, 4, row, "ROI tag(s)");
        // page.setLabel( 4 , row , "ROI tag(s)" );

        row++;

        int nb = 0;
        for (final ROI roi : ROI2Detection.keySet()) {
            // System.out.println("ROI id : " + roi.getId() );
            XLSXUtil.setCellNumber(page, 0, row, nb);
            // page.setNumber( 0 , row , nb );
            XLSXUtil.setCellString(page, 1, row, roi.getName());
            // page.setLabel( 1 , row , roi.getName() );
            // xlsManager.setLabel( 1 , row, "", roi.getColor() );
            XLSXUtil.setCellNumber(page, 2, row, computeROISurface(roi));
            // page.setNumber( 2 , row , computeROISurface(roi) );
            XLSXUtil.setCellNumber(page, 3, row, ROI2Detection.get(roi).size());
            // page.setNumber( 3 , row , ROI2Detection.get( roi ).size() );

            int xOffset = 4;
            // System.out.println("ok");
            // ---------------------------------------------------------- add ROI tag
            final Node tagNode = gdt.inputSequence.getNode("tags");
            if (tagNode != null) {

                final ArrayList<Element> roiElementList = XMLUtil.getElements(tagNode);

                for (final Element roiElement : roiElementList) {
                    final int roiId = XMLUtil.getAttributeIntValue(roiElement, "ROI_ID", -1);
                    // System.out.println("proposed : " + roiId );
                    if (roiId == roi.getId()) {
                        // System.out.println("match !");
                        final ArrayList<Element> roiTagList = XMLUtil.getElements(roiElement);

                        for (final Element tag : roiTagList) {
                            final String name = XMLUtil.getAttributeValue(tag, "name", "no name");
                            // System.out.println( name );
                            XLSXUtil.setCellString(page, xOffset, row, name);
                            // page.setLabel( xOffset , row , name );
                            xOffset++;

                        }
                    }
                }
            }
            // ----------------------------------------------------------

            row++;
            nb++;
        }

        // Save detection per ROI

        row++;
        row++;
        XLSXUtil.setCellString(page, 0, row, "Detection per ROI");
        // page.setLabel( 0 , row , "Detection per ROI" );

        int nbROI = 0;
        for (final ROI roi : ROI2Detection.keySet()) {
            row++;
            row++;
            XLSXUtil.setCellString(page, 0, row, "ROI Number:");
            // page.setLabel( 0 , row , "ROI Number: " );
            XLSXUtil.setCellNumber(page, 0, row, nbROI);
            // page.setNumber( 0 , row , nbROI );
            row++;
            row++;
            XLSXUtil.setCellString(page, 0, row, "Detection #");
            // page.setLabel( 0 , row , "Detection #" );
            XLSXUtil.setCellString(page, 1, row, "Surface");
            // page.setLabel( 1 , row , "Surface" );
            XLSXUtil.setCellString(page, 2, row, "x");
            // page.setLabel( 2 , row , "x" );
            XLSXUtil.setCellString(page, 3, row, "y");
            // page.setLabel( 3 , row , "y" );
            XLSXUtil.setCellString(page, 4, row, "z");
            // page.setLabel( 4 , row , "z" );
            XLSXUtil.setCellString(page, 5, row, "t");
            // page.setLabel( 5 , row , "t" );
            XLSXUtil.setCellString(page, 6, row, "min intensity");
            // page.setLabel( 6 , row , "min intensity" );
            XLSXUtil.setCellString(page, 7, row, "max intensity");
            // page.setLabel( 7 , row , "max intensity" );
            XLSXUtil.setCellString(page, 8, row, "average intensity");
            // page.setLabel( 8 , row , "average intensity" );
            row++;
            int detectionNumber = 0;
            for (final DetectionSpot detectionSpot : ROI2Detection.get(roi)) {
                XLSXUtil.setCellNumber(page, 0, row, detectionNumber);
                // page.setNumber( 0 , row , detectionNumber );
                XLSXUtil.setCellNumber(page, 1, row, detectionSpot.points.size());
                // page.setNumber( 1 , row , detectionSpot.points.size() );
                XLSXUtil.setCellNumber(page, 2, row, detectionSpot.getMassCenter().x);
                // page.setNumber( 2 , row , detectionSpot.getMassCenter().x );
                XLSXUtil.setCellNumber(page, 3, row, detectionSpot.getMassCenter().y);
                // page.setNumber( 3 , row , detectionSpot.getMassCenter().y );
                XLSXUtil.setCellNumber(page, 4, row, detectionSpot.getMassCenter().z);
                // page.setNumber( 4 , row , detectionSpot.getMassCenter().z );
                XLSXUtil.setCellNumber(page, 5, row, detectionSpot.getT());
                // page.setNumber( 5 , row , detectionSpot.getT() );
                XLSXUtil.setCellNumber(page, 6, row, detectionSpot.minIntensity);
                // page.setNumber( 6 , row , detectionSpot.minIntensity );
                XLSXUtil.setCellNumber(page, 7, row, detectionSpot.maxIntensity);
                // page.setNumber( 7 , row , detectionSpot.maxIntensity );
                XLSXUtil.setCellNumber(page, 8, row, detectionSpot.meanIntensity);
                // page.setNumber( 8 , row , detectionSpot.meanIntensity );
                row++;
                detectionNumber++;
            }

            row++;
            nbROI++;
        }

    }

    static int computeROISurface(final ROI roi) throws InterruptedException {
        return (int) ROIInteriorDescriptor.computeInterior(roi);
    }
}
